import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const wasmBytes = readFileSync(join(__dirname, '../wasm/pkg/clipper_offset_bg.wasm'));
const glueText  = readFileSync(join(__dirname, '../wasm/pkg/clipper_offset.js'), 'utf-8');

mkdirSync(join(__dirname, '../src/generated'), { recursive: true });
writeFileSync(
  join(__dirname, '../src/generated/wasm-data.ts'),
  `// Auto-generated by scripts/generate-wasm-data.mjs — do not edit\n` +
  `export const wasmBase64 = "${wasmBytes.toString('base64')}";\n` +
  `export const glueText = ${JSON.stringify(glueText)};\n`
);
console.log('Generated src/generated/wasm-data.ts');
